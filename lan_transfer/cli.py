from __future__ import annotations

import argparse
import os
import sys

# Ensure direct script execution (`python lan_transfer/cli.py` or PyInstaller) resolves package imports
if __package__ in (None, ""):
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lan_transfer import __version__
from lan_transfer.discover import discover_transfers
from lan_transfer.receiver import receive_file
from lan_transfer.sender import send_file


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="lan-transfer",
        description="LAN Transfer CLI - Ultra-fast, encrypted P2P file & folder transfer over local networks.",
        epilog=(
            "Examples:\n"
            "  Send file:      lan-transfer send \"C:\\Path\\To\\Video.mp4\" --users 3\n"
            "  Send folder:    lan-transfer send \"C:\\Path\\To\\Folder\" --compress\n"
            "  Receive:        lan-transfer receive 192.168.1.5:54321 Video.mp4 --pin 1234 --key A8X2...\n"
            "  Receive+Unpack: lan-transfer receive 192.168.1.5:54321 --pin 1234 --key A8X2... -x -o ./Downloads\n"
            "  Network Radar:  lan-transfer discover"
        ),
        formatter_class=argparse.RawTextHelpFormatter,
    )
    parser.add_argument(
        "-v",
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
    )

    subparsers = parser.add_subparsers(dest="command", help="Operation commands")

    # Sub-parser for Sending
    send_parser = subparsers.add_parser(
        "send",
        help="Opens a temporary encrypted server and exposes a file or folder for download.",
    )
    send_parser.add_argument(
        "filepath",
        type=str,
        help="Path of the file or directory to send.",
    )
    send_parser.add_argument(
        "-u",
        "--users",
        type=int,
        default=1,
        help="Number of completed downloads allowed before closing (default: 1).",
    )
    send_parser.add_argument(
        "-p",
        "--port",
        type=int,
        default=0,
        help="TCP port to bind (default: 0 for automatic free port).",
    )
    send_parser.add_argument(
        "--host",
        type=str,
        default=None,
        help="Specific local IP interface to advertise/bind (default: auto-detect LAN IP).",
    )
    send_parser.add_argument(
        "-z",
        "--compress",
        action="store_true",
        help="Stream folders with fast gzip compression (.tar.gz).",
    )
    send_parser.add_argument(
        "--expire",
        type=float,
        default=0.0,
        metavar="MINUTES",
        help="Auto-close server after MINUTES of inactivity (default: 0, disabled).",
    )

    # Sub-parser for Receiving
    receive_parser = subparsers.add_parser(
        "receive",
        help="Connects to a sender, verifies credentials, and downloads/resumes a transfer.",
    )
    receive_parser.add_argument(
        "address",
        type=str,
        help="IP and Port of the sender (e.g. 192.168.1.5:54321).",
    )
    receive_parser.add_argument(
        "filename",
        type=str,
        nargs="?",
        default=None,
        help="Optional filename (auto-detected from sender if omitted).",
    )
    receive_parser.add_argument(
        "--pin",
        type=str,
        required=True,
        help="4-digit security PIN.",
    )
    receive_parser.add_argument(
        "--key",
        type=str,
        required=True,
        help="AES-256 Base64 key generated by the sender.",
    )
    receive_parser.add_argument(
        "-o",
        "--output",
        type=str,
        default=None,
        help="Destination folder or output file path (default: current directory).",
    )
    receive_parser.add_argument(
        "-x",
        "--extract",
        action="store_true",
        help="Automatically extract received folder archives (.tar / .tar.gz).",
    )
    receive_parser.add_argument(
        "-f",
        "--overwrite",
        action="store_true",
        help="Overwrite target file if it already exists (default: auto-rename safely).",
    )
    receive_parser.add_argument(
        "--no-resume",
        action="store_true",
        help="Disable automatic download resume and start from byte 0.",
    )

    # Sub-parser for Discover
    discover_parser = subparsers.add_parser(
        "discover",
        help="Scans the local network via mDNS for active LAN Transfers.",
    )
    discover_parser.add_argument(
        "-t",
        "--timeout",
        type=float,
        default=3.0,
        help="Scan duration in seconds (default: 3.0).",
    )
    discover_parser.add_argument(
        "-o",
        "--output",
        type=str,
        default=None,
        help="Destination directory for downloaded transfers.",
    )

    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    if args.command == "send":
        send_file(
            filepath=args.filepath,
            users=args.users,
            port=args.port,
            host=args.host,
            compress=args.compress,
            expire_minutes=args.expire,
        )
    elif args.command == "receive":
        ok = receive_file(
            address=args.address,
            filename=args.filename,
            pin=args.pin,
            key_b64=args.key,
            output=args.output,
            extract=args.extract,
            overwrite=args.overwrite,
            resume=not args.no_resume,
        )
        if not ok:
            sys.exit(1)
    elif args.command == "discover":
        discover_transfers(scan_timeout=args.timeout, output=args.output)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
